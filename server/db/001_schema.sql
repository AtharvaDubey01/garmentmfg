-- View 1: SpineAttendance
-- Unrolls D1..D31 using CROSS JOIN LATERAL
CREATE OR REPLACE VIEW spineattendance AS
SELECT 
    t.id, 
    t.monthyear, 
    t.monthnm, 
    t.yearnm, 
    t.empcode, 
    cv.attributename, 
    cv.attributevalue
FROM dailyattandance t
CROSS JOIN LATERAL (VALUES 
    ('01', t.d1), ('02', t.d2), ('03', t.d3), ('04', t.d4), ('05', t.d5), ('06', t.d6), 
    ('07', t.d7), ('08', t.d8), ('09', t.d9), ('10', t.d10), ('11', t.d11), ('12', t.d12), 
    ('13', t.d13), ('14', t.d14), ('15', t.d15), ('16', t.d16), ('17', t.d17), ('18', t.d18), 
    ('19', t.d19), ('20', t.d20), ('21', t.d21), ('22', t.d22), ('23', t.d23), ('24', t.d24), 
    ('25', t.d25), ('26', t.d26), ('27', t.d27), ('28', t.d28), ('29', t.d29), ('30', t.d30), 
    ('31', t.d31)
) AS cv(attributename, attributevalue);

