-- View 9: LotGroupPivot
-- Replaces T-SQL PIVOT with conditional aggregation FILTER (WHERE ...)
CREATE OR REPLACE VIEW lotgrouppivot AS
SELECT 
    yearname, 
    monthname, 
    lotno, 
    fabricdtls, 
    cutqty, 
    SUM(totalqty) FILTER (WHERE ledgrpname = 'GROUP-A') AS "GROUP-A",
    SUM(totalqty) FILTER (WHERE ledgrpname = 'GROUP-B') AS "GROUP-B",
    SUM(totalqty) FILTER (WHERE ledgrpname = 'GROUP-C') AS "GROUP-C",
    SUM(totalqty) FILTER (WHERE ledgrpname = 'GROUP-D') AS "GROUP-D",
    SUM(totalqty) FILTER (WHERE ledgrpname = 'GROUP-E') AS "GROUP-E",
    SUM(totalqty) FILTER (WHERE ledgrpname = 'GROUP-F') AS "GROUP-F",
    SUM(totalqty) FILTER (WHERE ledgrpname = 'GROUP-G') AS "GROUP-G",
    SUM(totalqty) FILTER (WHERE ledgrpname = 'CUTTING') AS "CUTTING",
    SUM(totalqty) FILTER (WHERE ledgrpname = 'CUTTING-FUSING') AS "CUTTING-FUSING",
    SUM(totalqty) FILTER (WHERE ledgrpname = 'FINISHING') AS "FINISHING",
    SUM(totalqty) FILTER (WHERE ledgrpname = 'KAJ BUTTON') AS "KAJ BUTTON",
    SUM(totalqty) FILTER (WHERE ledgrpname = 'T/C') AS "T/C"
FROM lotgroupqty
GROUP BY yearname, monthname, lotno, fabricdtls, cutqty;
